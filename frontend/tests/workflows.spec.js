async function mindmapGeometry(page) {
  return page.locator('.zh-mindmap').evaluate(host => {
    const nodes=[...host.querySelectorAll('jmnode[nodeid]')].filter(el => getComputedStyle(el).display !== 'none')
    const overlaps=[]
    for(let i=0;i<nodes.length;i++) for(let j=i+1;j<nodes.length;j++) {
      const a=nodes[i].getBoundingClientRect(), b=nodes[j].getBoundingClientRect()
      if(Math.min(a.right,b.right)-Math.max(a.left,b.left)>1 && Math.min(a.bottom,b.bottom)-Math.max(a.top,b.top)>1)
        overlaps.push([nodes[i].getAttribute('nodeid'),nodes[j].getAttribute('nodeid')])
    }
    const clipped=nodes.filter(el => el.scrollWidth>el.clientWidth+1 || el.scrollHeight>el.clientHeight+1).map(el => el.getAttribute('nodeid'))
    return {overlaps,clipped}
  })
}

